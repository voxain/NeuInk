// Returns the pinned root PEM for a download URL, or nullptr to refuse it.
// Only https is accepted, and only for the hosts listed above. The host must end
// the authority (a path, port or query), so github.com.example.net does not match.
inline const char* rootFor(const std::string& url) {
  static constexpr char kPrefix[] = "https://";
  const size_t prefixLen = sizeof(kPrefix) - 1;
  if (url.compare(0, prefixLen, kPrefix) != 0) return nullptr;
  const size_t hostStart = prefixLen;
  size_t hostEnd = url.find_first_of(":/?", hostStart);
  if (hostEnd == std::string::npos) hostEnd = url.size();
  const std::string host = url.substr(hostStart, hostEnd - hostStart);
  if (host == "github.com") return kUsertrustEccRoot;
  if (host == "release-assets.githubusercontent.com" || host == "objects.githubusercontent.com") {
    return kIsrgRootX1;
  }
  return nullptr;
}

