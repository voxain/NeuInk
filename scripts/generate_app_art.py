"""
Draw the artwork of the built-in apps and write it as
src/activities/apps/AppArt.h:

- the chess pieces, from Lucide (ISC): the outline of each piece (the white
  piece), and the same shape filled in (the black piece, and the white piece's
  underlay, painted white first so it stays readable on a hatched square). Lucide
  is drawn on a 24-unit grid, so 48 px (the board) and 24 px (the captured
  pieces) are exact multiples and every stroke lands on whole pixels;
- the digits of the clock, from Lexend Deca (SIL Open Font License), in three
  sizes.

Everything is a one-bit bitmap, rows padded to whole bytes, most significant
bit first, 1 = ink.

Usage:
    python scripts/generate_app_art.py <lucide icons folder>
    (needs Pillow and rsvg-convert or inkscape; the folder is lucide-static's icons/)
"""

import io
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

REPO = Path(__file__).resolve().parent.parent
SOURCES = REPO / "lib" / "EpdFont" / "builtinFonts" / "source"
LEXEND_BOLD = SOURCES / "LexendDeca" / "LexendDeca-Bold.ttf"
OUTPUT = REPO / "src" / "activities" / "apps" / "AppArt.h"

PIECE = 48
SMALL_PIECE = 24
# King, queen, rook, bishop, knight, pawn.
PIECE_NAMES = ["King", "Queen", "Rook", "Bishop", "Knight", "Pawn"]
CLOCK_SETS = [("ClockLarge", 106), ("ClockMedium", 74), ("ClockSmall", 38)]
CLOCK_CHARACTERS = "0123456789:"


# --- chess pieces -------------------------------------------------------------------------------
def render_lucide(svg, size):
    """The icon as a size x size image, 255 where there is ink."""
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "icon.svg"
        source.write_text(Path(svg).read_text().replace("currentColor", "#000000"))
        if shutil.which("rsvg-convert"):
            png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), str(source)],
                                 capture_output=True, check=True).stdout
        else:
            target = Path(folder) / "icon.png"
            subprocess.run(["inkscape", str(source), "-w", str(size), "-h", str(size), "-o", str(target)],
                           capture_output=True, check=True)
            png = target.read_bytes()
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    white = Image.new("RGBA", image.size, (255, 255, 255, 255))
    white.paste(image, mask=image.split()[3])
    return white.convert("L").point(lambda v: 255 if v < 110 else 0)


def silhouette_of(ink):
    """The outline with its inside filled in: everything the outside cannot reach."""
    width, height = ink.size
    padded = Image.new("L", (width + 2, height + 2), 0)
    padded.paste(ink, (1, 1))
    ImageDraw.floodfill(padded, (0, 0), 128)
    return padded.point(lambda v: 0 if v == 128 else 255).crop((1, 1, width + 1, height + 1))


def rows_of(image):
    pixels = image.load()
    return [[pixels[x, y] > 127 for x in range(image.size[0])] for y in range(image.size[1])]


# --- clock digits -------------------------------------------------------------------------------
def font_for_height(path, reference, height):
    size = height
    best = ImageFont.truetype(str(path), size)
    while True:
        font = ImageFont.truetype(str(path), size)
        top, bottom = font.getbbox(reference)[1], font.getbbox(reference)[3]
        if bottom - top > height:
            return best
        best = font
        size += 1


def render_digits(font):
    top, bottom = font.getbbox("8")[1], font.getbbox("8")[3]
    rows = bottom - top
    glyphs = []
    for character in CLOCK_CHARACTERS:
        left, _, right, _ = font.getbbox(character)
        width = right - left
        image = Image.new("L", (width, rows), 0)
        ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255)
        pixels = image.load()
        glyphs.append((width, [[pixels[x, y] >= 128 for x in range(width)] for y in range(rows)]))
    return rows, glyphs


# --- output -------------------------------------------------------------------------------------
def pack(rows):
    data = []
    for row in rows:
        for start in range(0, len(row), 8):
            byte = 0
            for bit in range(8):
                byte = (byte << 1) | (1 if start + bit < len(row) and row[start + bit] else 0)
            data.append(byte)
    return data


def byte_lines(data):
    return "\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 20]) + "," for i in range(0, len(data), 20))


def bitmap(parts, name, rows):
    data = pack(rows)
    parts.append(f"inline constexpr uint8_t k{name}Bits[] = {{\n{byte_lines(data)}\n}};")
    parts.append(f"inline constexpr Bitmap k{name} = {{{len(rows[0])}, {len(rows)}, k{name}Bits}};\n")
    return len(data)


def main() -> None:
    total = 0
    parts = [
        "#pragma once\n",
        "#include <cstdint>\n",
        "// Generated by scripts/generate_app_art.py. Do not edit.",
        "//",
        "// Chess pieces from Lucide (ISC), clock digits from Lexend Deca (SIL Open Font License).",
        "// The button icons are Lucide too (src/components/icons/homeIcons.h).",
        "//",
        "// One-bit bitmaps: rows padded to whole bytes, most significant bit first, 1 = ink.\n",
        "namespace appart {\n",
        "struct Bitmap {\n  uint8_t width;\n  uint8_t height;\n  const uint8_t* bits;\n};\n",
        "struct Glyph {\n  uint16_t offset;  // into the set's bitmap bytes\n  uint8_t width;\n};\n",
    ]
    lucide = Path(sys.argv[1])
    parts.append("// Chess pieces (Lucide): the outline is the white piece, the filled shape the black piece and the")
    parts.append("// white piece's underlay. Kinds in the order king, queen, rook, bishop, knight, pawn.")
    for size, prefix in ((PIECE, "Piece"), (SMALL_PIECE, "SmallPiece")):
        for name in PIECE_NAMES:
            outline = render_lucide(lucide / f"chess-{name.lower()}.svg", size)
            total += bitmap(parts, f"{prefix}Outline{name}", rows_of(outline))
            total += bitmap(parts, f"{prefix}Silhouette{name}", rows_of(silhouette_of(outline)))
        for shape in ("Outline", "Silhouette"):
            parts.append(
                f"inline constexpr const Bitmap* k{prefix}{shape}[6] = {{"
                + ", ".join(f"&k{prefix}{shape}{name}" for name in PIECE_NAMES)
                + "};"
            )
        parts.append("")

    parts.append("// Clock digits: glyphs 0-9, then the colon. Every glyph of a set is k<Set>Rows high.")
    for name, height in CLOCK_SETS:
        font = font_for_height(LEXEND_BOLD, "8", height)
        rows, glyphs = render_digits(font)
        data = []
        table = []
        for width, glyph_rows in glyphs:
            table.append((len(data), width))
            data.extend(pack(glyph_rows))
        parts.append(f"constexpr int k{name}Rows = {rows};")
        parts.append(f"inline constexpr uint8_t k{name}Bits[] = {{\n{byte_lines(data)}\n}};")
        parts.append(
            f"inline constexpr Glyph k{name}Glyphs[{len(table)}] = {{\n    "
            + ", ".join(f"{{{offset}, {width}}}" for offset, width in table)
            + ",\n};\n"
        )
        total += len(data)
        print(f"{name}: {rows} rows, {len(data)} bytes, widest {max(w for _, w in table)} px")
    parts.append("}  // namespace appart")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}: {total} bytes of bitmaps")


if __name__ == "__main__":
    main()
